export const questionById = new Map(QUESTIONS.map((item) => [item.id, item]));
export function selectQuestions(track, count) {
  if (track !== 'all' && !TRACKS.some((item) => item.id === track)) throw new Error('未知面试方向');
  const pool = track === 'all' ? Array.from({ length: 3 }, (_, i) => TRACKS.map((item) => QUESTIONS.filter((q) => q.track === item.id)[i])).flat() : QUESTIONS.filter((q) => q.track === track);
  return pool.slice(0, count);
}
